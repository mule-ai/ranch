// RN <-> page protocol:
//   page -> RN  { t:"ready" }                     page is up, RN pushes the doc
//   page -> RN  { t:"change", value }             every doc change (no debounce —
//                                                 RN's draft/save must never be stale)
//   RN -> page  { t:"setDoc", value, mode }       load/replace the document
const glue = `
(function () {
  var editor = CodeMirror(document.body, {
    value: "",
    mode: "null",
    theme: "ranch",
    lineNumbers: true,
    matchBrackets: true,
    inputStyle: "contenteditable",
    indentUnit: 4,
    lineWrapping: false
  });
  editor.getWrapperElement().setAttribute("spellcheck", "false");
  editor.getWrapperElement().setAttribute("autocorrect", "off");
  editor.getWrapperElement().setAttribute("autocapitalize", "none");

  function send(msg) {
    if (window.ReactNativeWebView) window.ReactNativeWebView.postMessage(JSON.stringify(msg));
  }

  function onDocChanged() {
    send({ t: "change", value: editor.getValue() });
  }
  editor.on("change", onDocChanged);
  // last flush if the app backgrounds mid-keystroke
  document.addEventListener("visibilitychange", function () {
    if (document.hidden) send({ t: "change", value: editor.getValue() });
  });

  // react-native-webview on Android delivers webviewRef.postMessage here
  document.addEventListener("message", function (e) {
    var msg;
    try { msg = JSON.parse(e.data); } catch (err) { return; }
    if (msg.t === "setDoc") {
      if (msg.mode) editor.setOption("mode", msg.mode);
      var cur = editor.getValue();
      if (cur !== msg.value) {
        editor.setValue(msg.value);
        editor.clearHistory(); // fresh document, fresh undo stack
        editor.scrollTo(0, 0);
      }
    }
  });

  send({ t: "ready" });
})();
`;

const html = `<!doctype html>
<html><head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1, maximum-scale=1, user-scalable=no">
<style>
  html, body { margin: 0; padding: 0; background: #0a0a0e; }
  .CodeMirror { height: 100vh; }
</style>
<style>${css}</style>
<style>${theme}</style>
</head><body>
${files.map((js) => `<script>${js}</script>`).join("\n")}
<script>${glue}</script>
</body></html>`;

const out = join(dir, "..", "..", "lib", "editor-html.ts");
writeFileSync(
  out,
  `// GENERATED by assets/editor/build.mjs — do not edit by hand.\n` +
    `// CodeMirror 5 + modes, inlined as one HTML document for the WebView editor.\n` +
    `export const EDITOR_HTML = ${JSON.stringify(html)};\n`
);
console.log(
  `editor-html.ts written (${(html.length / 1024).toFixed(0)} KB, ${files.length} inlined scripts)`
);
